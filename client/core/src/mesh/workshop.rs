//! Workshop equipment, normalized to a unit volume for map placement.
use super::models::Model;
use super::{MeshBuilder, Vertex};
pub fn build(model: Model) -> Vec<Vertex> {
    let mut m = MeshBuilder::default();
    match model {
        Model::Transformer => {
            m.block([0., -0.44, 0.], [0.98, 0.12, 0.86], 12);
            m.bevel([0., -0.04, 0.], [0.34, 0.32], [0.34, 0.32], 0.66, 16);
            for x in [-0.44, 0.44] {
                for z in [-0.28, -0.14, 0., 0.14, 0.28] {
                    m.block([x, -0.04, z], [0.08, 0.60, 0.06], 21);
                }
            }
            for x in [-0.22, 0., 0.22] {
                m.bevel([x, 0.38, 0.], [0.045, 0.045], [0.045, 0.045], 0.22, 17);
                for y in [0.31, 0.37, 0.43] {
                    m.bevel([x, y, 0.], [0.075, 0.075], [0.075, 0.075], 0.025, 17);
                }
            }
            m.block([0., -0.05, 0.33], [0.27, 0.18, 0.025], 24);
        }
        Model::Compressor => {
            m.block([0., -0.44, 0.], [0.95, 0.12, 0.85], 12);
            m.tube_x(-0.42, -0.15, 0., 0.84, 0.24, 18);
            m.bevel([0., 0.20, 0.], [0.23, 0.18], [0.23, 0.18], 0.26, 6);
            for x in [-0.17, -0.09, 0., 0.09, 0.17] {
                m.block([x, 0.24, 0.], [0.025, 0.32, 0.43], 21);
            }
            m.block([0.31, 0.15, 0.], [0.08, 0.42, 0.08], 19);
            m.block([0.30, 0.36, 0.05], [0.20, 0.20, 0.06], 24);
            m.block([-0.28, 0.14, 0.26], [0.09, 0.42, 0.09], 30);
        }
        Model::ServerRack => {
            m.bevel([0., 0., 0.], [0.42, 0.38], [0.42, 0.38], 1., 12);
            for y in [-0.37, -0.18, 0.01, 0.20, 0.39] {
                m.block([0., y, 0.39], [0.72, 0.16, 0.04], 16);
                m.block([-0.12, y, 0.416], [0.35, 0.10, 0.012], 21);
                m.block([0.23, y, 0.42], [0.12, 0.07, 0.018], 25);
            }
            for x in [-0.37, 0.37] {
                m.block([x, 0., 0.43], [0.035, 0.9, 0.035], 6);
            }
        }
        Model::Workbench => {
            for x in [-0.43, 0.43] {
                for z in [-0.30, 0.30] {
                    m.block([x, -0.12, z], [0.07, 0.76, 0.07], 16);
                }
            }
            m.block([0., 0.28, 0.], [1., 0.10, 0.8], 20);
            m.block([0., -0.32, 0.], [0.85, 0.06, 0.6], 12);
            m.block([-0.30, 0.38, 0.12], [0.19, 0.10, 0.23], 6);
            m.block([-0.30, 0.44, 0.12], [0.30, 0.10, 0.11], 6);
            m.tube_x(-0.48, 0.40, 0.16, 0.34, 0.022, 12);
            m.block([0.22, 0.36, -0.1], [0.32, 0.05, 0.29], 22);
        }
        Model::ToolChest => {
            m.bevel([0., 0., 0.], [0.44, 0.36], [0.44, 0.36], 0.82, 18);
            for y in [-0.27, -0.09, 0.09, 0.27] {
                m.block([0., y, 0.37], [0.78, 0.15, 0.025], 18);
                m.block([0., y + 0.035, 0.40], [0.55, 0.022, 0.045], 6);
            }
            m.block([0., 0.43, 0.], [0.94, 0.06, 0.78], 23);
            for x in [-0.33, 0.33] {
                for z in [-0.26, 0.26] {
                    m.tube_x(x - 0.04, -0.43, z, 0.08, 0.065, 23);
                }
            }
        }
        Model::PipeManifold => {
            m.block([0., 0., -0.40], [1., 1., 0.10], 16);
            for x in [-0.30, 0., 0.30] {
                m.bevel([x, 0., -0.12], [0.065, 0.065], [0.065, 0.065], 0.96, 19);
                m.block([x, 0.13, 0.02], [0.08, 0.08, 0.24], 6);
                m.block([x, 0.13, 0.16], [0.20, 0.035, 0.035], 18);
                m.block([x, 0.13, 0.16], [0.035, 0.20, 0.035], 18);
                m.block([x, -0.23, -0.03], [0.20, 0.17, 0.05], 24);
            }
        }
        Model::CableTray => {
            for x in [-0.45, 0.45] {
                m.block([x, 0., 0.], [0.07, 0.4, 1.], 28);
            }
            for z in [-0.44, -0.22, 0., 0.22, 0.44] {
                m.block([0., -0.16, z], [0.9, 0.06, 0.06], 6);
            }
            for x in [-0.27, -0.09, 0.09, 0.27] {
                m.block([x, -0.08, 0.], [0.10, 0.10, 0.98], if x > 0. { 29 } else { 30 });
            }
        }
        Model::Floodlight => {
            m.block([0., -0.46, 0.], [0.9, 0.08, 0.7], 12);
            m.block([0., -0.08, 0.], [0.10, 0.76, 0.10], 6);
            m.block([0., 0.27, 0.], [0.80, 0.06, 0.08], 6);
            for x in [-0.25, 0.25] {
                m.bevel([x, 0.35, 0.], [0.20, 0.10], [0.18, 0.09], 0.28, 16);
                m.block([x, 0.35, 0.11], [0.30, 0.18, 0.025], 15);
                for dx in [-0.08, 0.08] {
                    m.block([x + dx, 0.35, 0.13], [0.015, 0.24, 0.02], 6);
                }
            }
        }
        Model::Forklift => {
            m.bevel([0., -0.23, -0.13], [0.37, 0.33], [0.34, 0.29], 0.30, 29);
            for x in [-0.37, 0.29] {
                for z in [-0.33, 0.14] {
                    m.tube_x(x, -0.32, z, 0.08, 0.13, 23);
                }
            }
            m.block([0., 0., -0.28], [0.30, 0.10, 0.23], 23);
            m.block([0., 0.13, -0.38], [0.30, 0.23, 0.06], 23);
            for x in [-0.30, 0.30] {
                for z in [-0.39, 0.15] {
                    m.block([x, 0.19, z], [0.045, 0.57, 0.045], 12);
                }
            }
            m.block([0., 0.47, -0.12], [0.72, 0.05, 0.65], 29);
            for x in [-0.22, 0.22] {
                m.block([x, 0., 0.24], [0.065, 0.92, 0.07], 12);
                m.block([x, -0.40, 0.36], [0.10, 0.045, 0.28], 6);
            }
            m.block([0., -0.23, 0.28], [0.57, 0.20, 0.025], 26);
            m.block([0., 0.04, 0.06], [0.24, 0.05, 0.08], 12);
        }
        Model::VentDuct => {
            m.block([0., 0., 0.], [0.84, 0.78, 0.82], 28);
            for z in [-0.44, 0.44] {
                m.block([0., 0., z], [1., 0.94, 0.07], 6);
                m.block([0., 0., z * 1.1], [0.72, 0.65, 0.015], 27);
            }
            for y in [-0.30, -0.15, 0., 0.15, 0.30] {
                m.block([0., y, 0.49], [0.78, 0.03, 0.02], 12);
            }
        }
        Model::PressureValve => {
            m.tube_x(-0.5, -0.18, 0., 1., 0.19, 19);
            for x in [-0.43, 0.36] {
                m.tube_x(x, -0.18, 0., 0.07, 0.27, 6);
            }
            m.bevel([0., 0.08, 0.], [0.08, 0.08], [0.08, 0.08], 0.35, 6);
            m.bevel([0., 0.32, 0.], [0.31, 0.31], [0.31, 0.31], 0.05, 18);
            m.block([0., 0.40, 0.], [0.035, 0.11, 0.035], 6);
        }
        Model::CoolingUnit => {
            m.bevel([0., -0.02, 0.], [0.45, 0.43], [0.45, 0.43], 0.9, 16);
            for x in [-0.24, 0.24] {
                m.block([x, 0.08, 0.44], [0.38, 0.52, 0.025], 21);
                m.block([x, 0.08, 0.47], [0.12, 0.12, 0.025], 6);
            }
            m.block([0., -0.31, 0.45], [0.50, 0.12, 0.025], 31);
            for x in [-0.39, 0.39] {
                m.block([x, -0.47, 0.], [0.14, 0.06, 0.90], 12);
            }
        }
        _ => unreachable!("non-workshop model"),
    }
    m.0
}
