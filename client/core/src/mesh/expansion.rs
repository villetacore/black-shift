//! Original low-poly industrial expansion, sharing the game's material palette.
use super::models::Model;
use super::{MeshBuilder, Vertex};
pub fn build(model: Model) -> Vec<Vertex> {
    let mut m = MeshBuilder::default();
    match model {
        Model::Pallet => {
            for x in [-0.4, 0., 0.4] {
                m.block([x, -0.16, 0.], [0.15, 0.68, 1.], 14);
            }
            for z in [-0.42, -0.21, 0., 0.21, 0.42] {
                m.block([0., 0.36, z], [1., 0.28, 0.16], 14);
                m.block([0., -0.42, z], [1., 0.16, 0.16], 14);
            }
        }
        Model::Console => {
            m.block([0., -0.13, 0.], [0.92, 0.74, 0.85], 5);
            m.block([0., 0.3, -0.12], [1., 0.4, 0.6], 12);
            m.block([-0.14, 0.32, 0.19], [0.49, 0.24, 0.025], 11);
            for y in [0.25, 0.32, 0.39] {
                m.block([-0.18, y, 0.21], [0.32, 0.014, 0.015], 8);
            }
            for x in [-0.3, -0.1, 0.1, 0.3] {
                m.block([x, 0.08, 0.39], [0.1, 0.05, 0.08], 6);
            }
            m.block([0.32, 0.34, 0.2], [0.09, 0.09, 0.03], 15);
        }
        Model::Generator => {
            m.block([0., -0.42, 0.], [1., 0.16, 1.], 12);
            m.bevel([0., -0.02, 0.], [0.43, 0.40], [0.32, 0.35], 0.65, 5);
            for x in [-0.36, -0.24, -0.12, 0., 0.12, 0.24, 0.36] {
                m.block([x, 0., 0.42], [0.045, 0.4, 0.07], 6);
            }
            m.block([-0.25, 0.38, -0.2], [0.09, 0.24, 0.09], 12);
            m.block([0.24, 0.31, 0.], [0.24, 0.08, 0.35], 9);
        }
        Model::Tank => {
            m.bevel([0., -0.02, 0.], [0.38, 0.38], [0.38, 0.38], 0.8, 6);
            for y in [-0.36, 0.32] {
                m.bevel([0., y, 0.], [0.43, 0.43], [0.43, 0.43], 0.07, 12);
            }
            m.bevel([0., 0.4, 0.], [0.38, 0.38], [0.14, 0.14], 0.12, 6);
            m.block([0., 0.48, 0.], [0.18, 0.04, 0.18], 9);
            for x in [-0.28, 0.28] {
                m.block([x, -0.45, 0.], [0.14, 0.1, 0.6], 12);
            }
        }
        Model::Pump => {
            m.block([0., -0.43, 0.], [1., 0.14, 0.8], 12);
            m.tube_x(-0.42, -0.02, 0., 0.84, 0.25, 6);
            for x in [-0.37, 0.3] {
                m.tube_x(x, -0.02, 0., 0.07, 0.34, 14);
            }
            m.block([0., 0.27, 0.], [0.12, 0.3, 0.12], 6);
            m.block([0., 0.43, 0.], [0.5, 0.07, 0.08], 9);
            m.block([0., 0.43, 0.], [0.08, 0.07, 0.5], 9);
        }
        Model::CableSpool => {
            m.tube_x(-0.4, 0., 0., 0.8, 0.30, 12);
            for x in [-0.46, 0.37] {
                m.tube_x(x, 0., 0., 0.09, 0.5, 14);
            }
            for x in [-0.3, -0.2, -0.1, 0., 0.1, 0.2, 0.3] {
                m.tube_x(x, 0., 0., 0.035, 0.33, 6);
            }
        }
        Model::Bollard => {
            m.block([0., -0.46, 0.], [1., 0.08, 1.], 12);
            m.bevel([0., 0., 0.], [0.23, 0.23], [0.23, 0.23], 1., 9);
            for y in [-0.2, 0.2] {
                m.block([0., y, 0.], [0.48, 0.16, 0.48], 12);
            }
        }
        Model::Lamp => {
            m.block([0., 0., -0.3], [1., 1., 0.4], 12);
            m.block([0., 0., -0.07], [0.82, 0.72, 0.12], 15);
            for x in [-0.3, 0., 0.3] {
                m.block([x, 0., 0.04], [0.04, 0.85, 0.06], 6);
            }
        }
        Model::Barricade => {
            m.bevel([0., 0., 0.], [0.5, 0.5], [0.5, 0.23], 1., 1);
            m.block([0., 0.21, 0.34], [0.96, 0.2, 0.03], 9);
            m.block([0., 0.21, -0.34], [0.96, 0.2, 0.03], 9);
        }
        Model::Fan => {
            m.block([0., 0., -0.1], [1., 1., 0.5], 12);
            for a in [0., 1.5707964, 3.1415927, 4.712389] {
                let (s, c) = f32::sin_cos(a);
                m.block([c * 0.22, s * 0.22, 0.2], [0.22, 0.22, 0.04], 6);
            }
            m.block([0., 0., 0.23], [0.17, 0.17, 0.06], 9);
            for x in [-0.4, -0.2, 0., 0.2, 0.4] {
                m.block([x, 0., 0.28], [0.025, 0.9, 0.025], 2);
            }
        }
        Model::Shotgun | Model::Smg => {
            let shotgun = model == Model::Shotgun;
            m.block([0., 0., 0.], [0.38, 0.16, 0.13], 12);
            m.bevel([-0.31, -0.015, 0.], [0.21, 0.07], [0.2, 0.055], 0.14, 14);
            m.block([-0.08, -0.15, 0.], [0.09, 0.23, 0.10], 12);
            m.tube_x(0.18, 0.025, 0., if shotgun { 0.64 } else { 0.4 }, 0.035, 6);
            m.tube_x(0.18, -0.045, 0., 0.38, 0.035, 12);
            m.block(
                [0.38, -0.05, 0.],
                [0.25, 0.11, 0.12],
                if shotgun { 14 } else { 5 },
            );
            m.block([0.03, 0.11, 0.], [0.06, 0.055, 0.08], 6);
            if !shotgun {
                m.block([0.14, -0.2, 0.], [0.09, 0.32, 0.075], 6);
            }
            m.bevel([-0.10, -0.23, 0.08], [0.075, 0.06], [0.075, 0.06], 0.14, 7);
            m.bevel([0.35, -0.13, -0.04], [0.09, 0.07], [0.09, 0.07], 0.09, 7);
        }
        Model::WardenGear => {
            m.block([-0.27, 1.19, 0.], [0.19, 0.43, 0.37], 12);
            for z in [-0.14, 0.14] {
                m.bevel([-0.35, 1.2, z], [0.09, 0.08], [0.09, 0.08], 0.38, 6);
            }
            m.block([0.19, 1.61, 0.], [0.11, 0.11, 0.22], 12);
            for z in [-0.32, 0.32] {
                m.block([0., 1.40, z], [0.30, 0.12, 0.18], 5);
            }
        }
        Model::RangerGear => {
            m.block([-0.25, 1.2, -0.12], [0.13, 0.23, 0.16], 4);
            m.block([-0.25, 1.5, -0.12], [0.018, 0.40, 0.018], 6);
            for z in [-0.16, 0., 0.16] {
                m.block([0.23, 1.06, z], [0.10, 0.18, 0.11], 4);
            }
        }
        _ => unreachable!("base model routed to expansion"),
    }
    m.0
}
